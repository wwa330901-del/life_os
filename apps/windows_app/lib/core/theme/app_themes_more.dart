const _sans = 'Noto Sans TC';
const _serif = 'Noto Serif TC';

AppThemeSpec _solid({
  required String id,
  required String name,
  required String description,
  required Color top,
  required Color bottom,
  required Color primary,
  Color onPrimary = const Color(0xFFFFFFFF),
  required Color text,
  required Color sub,
  required Color accent,
  required Color chipBg,
  bool dark = false,
  String headFont = _sans,
  double cardRadius = 16,
  double buttonRadius = 12,
  double chipRadius = 12,
}) => AppThemeSpec(
  id: id,
  name: name,
  description: description,
  series: ThemeSeries.solid,
  brightness: dark ? Brightness.dark : Brightness.light,
  gradient: [top, bottom],
  ground: bottom,
  panel: dark ? Color.lerp(top, const Color(0xFFFFFFFF), 0.06)! : Color.lerp(bottom, const Color(0xFFFFFFFF), 0.4)!,
  text: text,
  sub: sub,
  primary: primary,
  onPrimary: onPrimary,
  accent: accent,
  card: dark ? const Color(0x14FFFFFF) : const Color(0xD9FFFFFF),
  border: dark ? const Color(0x24FFFFFF) : const Color(0x14000000),
  track: dark ? const Color(0x1FFFFFFF) : const Color(0x14000000),
  chipBg: chipBg,
  headFont: headFont,
  bodyFont: _sans,
  cardRadius: cardRadius,
  buttonRadius: buttonRadius,
  chipRadius: chipRadius,
);

AppThemeSpec _photo({
