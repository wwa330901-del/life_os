  required String name,
  required String description,
  required Color ground,
  required Color primary,
  required Color accent,
  required Color chipBg,
  bool dark = false,
}) => AppThemeSpec(
  id: id,
  name: name,
  description: description,
  series: ThemeSeries.photo,
  brightness: dark ? Brightness.dark : Brightness.light,
  ground: ground,
  panel: dark ? const Color(0xFF1C2129) : const Color(0xFFF2F2EF),
  text: dark ? const Color(0xFFF4F6F8) : const Color(0xFF1C2228),
  sub: dark ? const Color(0xFFC3C9D1) : const Color(0xFF4E565E),
  primary: primary,
  onPrimary: dark ? const Color(0xFF16110A) : const Color(0xFFFFFFFF),
  accent: accent,
  card: dark ? const Color(0xB814181E) : const Color(0xD1FFFFFF),
  border: dark ? const Color(0x2EFFFFFF) : const Color(0x12000000),
  track: dark ? const Color(0x26FFFFFF) : const Color(0x14000000),
  chipBg: chipBg,
  headFont: _sans,
  bodyFont: _sans,
  cardRadius: 16,
  buttonRadius: 12,
  chipRadius: 12,
);

